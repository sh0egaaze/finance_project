def fill_template(template: str) -> str:
    result = template

    replacements = {
        "{branch}": lambda: random.choice(BRANCHES),
        "{restaurant_name}": lambda: random.choice(RESTAURANT_NAMES),
        "{pharmacy_name}": lambda: random.choice(PHARMACY_NAMES),
        "{person_name}": lambda: random.choice(PERSON_NAMES),
        "{month}": lambda: random.choice(MONTHS),
        "{company}": lambda: random.choice(COMPANIES),
        "{route}": lambda: random.choice(ROUTES),
        "{card}": lambda: random.choice(CARDS),
        "{phone}": lambda: random.choice(PHONES),
        "{hotel_name}": lambda: random.choice(HOTEL_NAMES),
        "{subject}": lambda: random.choice(SUBJECTS),
        "{service}": lambda: random.choice(SERVICES),
        "{animal}": lambda: random.choice(ANIMALS),
        "{number}": lambda: random.choice(NUMBERS),
    }

    for placeholder, value_fn in replacements.items():
        if placeholder in result:
            result = result.replace(placeholder, value_fn())

    result = " ".join(result.split())
    return result.strip()


def add_noise(text: str) -> str:
    r = random.random()
    if r < 0.25:
        return text.upper()
    elif r < 0.45:
        return text.lower()
    elif r < 0.55:
        return text + f" {random.randint(1, 9999):04d}"
    elif r < 0.62:
        return text + f" от {random.randint(1,28)}.{random.randint(1,12):02d}"
    elif r < 0.67:
        return "Оплата: " + text
    elif r < 0.72:
        return "Списание: " + text
    elif r < 0.75:
        return "Покупка: " + text
    else:
        return text


def generate_dataset(
    num_samples: int = 200000,
    output_path: str = "data/transactions.csv",
) -> None:
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    categories = list(CATEGORIES.keys())
    total_weight = sum(CATEGORIES[c]["weight"] for c in categories)

    samples_per_category = {}
    for cat in categories:
        w = CATEGORIES[cat]["weight"]
        samples_per_category[cat] = max(200, int(num_samples * w / total_weight))

    current_total = sum(samples_per_category.values())
    diff = num_samples - current_total
    if diff > 0:
        weighted_cats = random.choices(
            categories,
            weights=[CATEGORIES[c]["weight"] for c in categories],
            k=diff,
        )
        for cat in weighted_cats:
            samples_per_category[cat] += 1

    data = []

    for category in categories:
        cat_info = CATEGORIES[category]
        templates = cat_info["templates"]
        amount_min, amount_max = cat_info["amount_range"]
        n_samples = samples_per_category[category]

        for _ in range(n_samples):
            template = random.choice(templates)
            description = fill_template(template)
            description = add_noise(description)
            amount = round(random.uniform(amount_min, amount_max), 2)

            data.append({
                "description": description,
                "category": category,
                "category_name": cat_info["name"],
                "amount": amount,
            })

    random.shuffle(data)

    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=["description", "category", "category_name", "amount"],
        )
        writer.writeheader()
        writer.writerows(data)

    print(f"\n✅ Датасет сгенерирован: {len(data):,} записей")
    print(f"   Сохранён: {output_path}")
    print(f"\n📊 Распределение:")
    for cat in categories:
        count = samples_per_category[cat]
        name = CATEGORIES[cat]["name"]
        bar = "█" * (count // 1500)
        print(f"   {cat:20s} ({name:25s}): {count:7,} {bar}")


